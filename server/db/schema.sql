-- Service Connect - PostgreSQL schema
--
-- This file is the authoritative, idempotent schema for the project.
-- It was reconstructed from the legacy `data_base.sql` pg_dump archive
-- (PostgreSQL 18, custom format) so it can be applied by both:
--   * local development (`npm run migrate`), and
--   * the Docker entrypoint (automatic on first container start).
--
-- Every statement is safe to re-run: existing tables are left untouched,
-- which means applying this file to an already-provisioned database is a no-op.

BEGIN;

-- ---------------------------------------------------------------------------
-- Users
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    email character varying(255) NOT NULL,
    password_hash character varying(255) NOT NULL,
    role character varying(50) NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    otp_code character varying(6),
    otp_expiry timestamp with time zone,
    status character varying(50) DEFAULT 'active' NOT NULL,
    profile_picture_url text,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT users_email_key UNIQUE (email),
    CONSTRAINT users_role_check CHECK (role IN ('customer', 'provider', 'admin'))
);

-- ---------------------------------------------------------------------------
-- Services catalogue
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS services (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    name character varying(100) NOT NULL,
    description text,
    icon_url character varying(255),
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT services_pkey PRIMARY KEY (id),
    CONSTRAINT services_name_key UNIQUE (name)
);

-- ---------------------------------------------------------------------------
-- Provider profiles
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS providers (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    user_id integer NOT NULL,
    display_name character varying(100) NOT NULL,
    bio text,
    location_lat numeric(10,8),
    location_lon numeric(11,8),
    service_radius_km integer,
    is_verified boolean DEFAULT false,
    profile_photo_url character varying(255),
    average_rating numeric(3,2) DEFAULT 0.00,
    review_count integer DEFAULT 0,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    payout_upi_id character varying(255),
    CONSTRAINT providers_pkey PRIMARY KEY (id),
    CONSTRAINT providers_user_id_key UNIQUE (user_id),
    CONSTRAINT providers_user_id_fkey FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS provider_services (
    provider_id integer NOT NULL,
    service_id integer NOT NULL,
    rate_per_hour numeric(10,2),
    CONSTRAINT provider_services_pkey PRIMARY KEY (provider_id, service_id),
    CONSTRAINT provider_services_provider_id_fkey FOREIGN KEY (provider_id) REFERENCES providers(id) ON DELETE CASCADE,
    CONSTRAINT provider_services_service_id_fkey FOREIGN KEY (service_id) REFERENCES services(id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------------
-- Customer profiles
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS customer_profiles (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    user_id integer NOT NULL,
    full_name character varying(255) DEFAULT 'New Customer'::character varying,
    phone_number character varying(20),
    address_line_1 character varying(255),
    city character varying(100),
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    location_lat numeric(10,8) DEFAULT 0,
    location_lon numeric(11,8) DEFAULT 0,
    CONSTRAINT customer_profiles_pkey PRIMARY KEY (id),
    CONSTRAINT customer_profiles_user_id_key UNIQUE (user_id),
    CONSTRAINT customer_profiles_user_id_fkey FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------------
-- Bookings + chat
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS bookings (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    customer_id integer NOT NULL,
    provider_id integer NOT NULL,
    service_id integer NOT NULL,
    booking_status character varying(50) NOT NULL,
    requested_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    scheduled_at timestamp with time zone,
    address text NOT NULL,
    customer_notes text,
    provider_notes text,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    service_description text,
    amount numeric(10,2),
    CONSTRAINT bookings_pkey PRIMARY KEY (id),
    CONSTRAINT bookings_customer_id_fkey FOREIGN KEY (customer_id) REFERENCES users(id),
    CONSTRAINT bookings_provider_id_fkey FOREIGN KEY (provider_id) REFERENCES providers(id),
    CONSTRAINT bookings_service_id_fkey FOREIGN KEY (service_id) REFERENCES services(id),
    CONSTRAINT bookings_booking_status_check CHECK (booking_status IN (
        'pending_provider',
        'awaiting_customer_confirmation',
        'accepted',
        'rejected',
        'completed',
        'closed'
    ))
);

CREATE TABLE IF NOT EXISTS messages (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    booking_id integer,
    sender_id integer NOT NULL,
    recipient_id integer NOT NULL,
    content text NOT NULL,
    is_read boolean DEFAULT false,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    file_url text,
    CONSTRAINT messages_pkey PRIMARY KEY (id),
    CONSTRAINT messages_booking_id_fkey FOREIGN KEY (booking_id) REFERENCES bookings(id) ON DELETE CASCADE,
    CONSTRAINT messages_sender_id_fkey FOREIGN KEY (sender_id) REFERENCES users(id),
    CONSTRAINT messages_recipient_id_fkey FOREIGN KEY (recipient_id) REFERENCES users(id)
);

-- ---------------------------------------------------------------------------
-- Payments, reviews, wallet
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS payments (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    booking_id integer NOT NULL,
    amount numeric(10,2) NOT NULL,
    status character varying(50) NOT NULL,
    gateway_transaction_id character varying(255),
    paid_at timestamp with time zone,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT payments_pkey PRIMARY KEY (id),
    CONSTRAINT payments_booking_id_key UNIQUE (booking_id),
    CONSTRAINT payments_gateway_transaction_id_key UNIQUE (gateway_transaction_id),
    CONSTRAINT payments_booking_id_fkey FOREIGN KEY (booking_id) REFERENCES bookings(id),
    CONSTRAINT payments_status_check CHECK (status IN ('pending', 'succeeded', 'failed'))
);

CREATE TABLE IF NOT EXISTS reviews (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    booking_id integer NOT NULL,
    customer_id integer NOT NULL,
    provider_id integer NOT NULL,
    rating integer NOT NULL,
    comment text,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT reviews_pkey PRIMARY KEY (id),
    CONSTRAINT reviews_booking_id_key UNIQUE (booking_id),
    CONSTRAINT reviews_booking_id_fkey FOREIGN KEY (booking_id) REFERENCES bookings(id),
    CONSTRAINT reviews_rating_check CHECK (rating >= 1 AND rating <= 5)
);

CREATE TABLE IF NOT EXISTS transactions (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    user_id integer,
    type character varying(50) NOT NULL,
    amount numeric(10,2) NOT NULL,
    related_id integer,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT transactions_pkey PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS wallets (
    user_id integer NOT NULL,
    balance numeric(10,2) DEFAULT 0.00 NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT wallets_pkey PRIMARY KEY (user_id)
);

CREATE TABLE IF NOT EXISTS wallet_requests (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    user_id integer NOT NULL,
    type character varying(50) NOT NULL,
    amount numeric(10,2) NOT NULL,
    transaction_reference text,
    screenshot_url text,
    status character varying(50) DEFAULT 'pending' NOT NULL,
    requested_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    processed_at timestamp with time zone,
    CONSTRAINT wallet_requests_pkey PRIMARY KEY (id),
    CONSTRAINT wallet_requests_type_check CHECK (type IN ('deposit', 'withdrawal')),
    CONSTRAINT wallet_requests_status_check CHECK (status IN ('pending', 'approved', 'rejected'))
);

-- ---------------------------------------------------------------------------
-- Contact + legacy auth/request tables (kept for compatibility with the dump)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS contact_messages (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    sender_name character varying(255) NOT NULL,
    sender_email character varying(255) NOT NULL,
    message text NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    is_resolved boolean DEFAULT false NOT NULL,
    CONSTRAINT contact_messages_pkey PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS otps (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    user_id integer NOT NULL,
    otp_code character varying(6) NOT NULL,
    expires_at timestamp with time zone NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT otps_pkey PRIMARY KEY (id),
    CONSTRAINT otps_user_id_key UNIQUE (user_id),
    CONSTRAINT otps_user_id_fkey FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS password_resets (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    email character varying(255) NOT NULL,
    otp character varying(6) NOT NULL,
    expires_at timestamp with time zone NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT password_resets_pkey PRIMARY KEY (id),
    CONSTRAINT password_resets_email_key UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS deposit_requests (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    user_id integer NOT NULL,
    amount numeric(10,2) NOT NULL,
    transaction_id character varying(255) NOT NULL,
    screenshot_url text,
    status character varying(50) DEFAULT 'pending' NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    processed_at timestamp with time zone,
    CONSTRAINT deposit_requests_pkey PRIMARY KEY (id),
    CONSTRAINT deposit_requests_user_id_fkey FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS withdrawal_requests (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    user_id integer NOT NULL,
    amount numeric(10,2) NOT NULL,
    payout_upi_id character varying(255),
    status character varying(50) DEFAULT 'pending' NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP,
    processed_at timestamp with time zone,
    CONSTRAINT withdrawal_requests_pkey PRIMARY KEY (id)
);

-- ---------------------------------------------------------------------------
-- Indexes used by the API queries
-- ---------------------------------------------------------------------------
CREATE UNIQUE INDEX IF NOT EXISTS idx_customer_profiles_user_id ON customer_profiles USING btree (user_id);
CREATE INDEX IF NOT EXISTS idx_messages_booking_id ON messages USING btree (booking_id);
CREATE INDEX IF NOT EXISTS idx_messages_recipient_unread ON messages USING btree (recipient_id, is_read);
CREATE INDEX IF NOT EXISTS idx_bookings_customer_id ON bookings USING btree (customer_id);
CREATE INDEX IF NOT EXISTS idx_bookings_provider_id ON bookings USING btree (provider_id);
CREATE INDEX IF NOT EXISTS idx_provider_services_service_id ON provider_services USING btree (service_id);
CREATE INDEX IF NOT EXISTS idx_wallet_requests_status ON wallet_requests USING btree (status, type);

COMMIT;
